    fun translate(
        language: Language,
        key: String,
        variables: Map<String, Any> = emptyMap()
    ): String {
        val source = if (language == Language.MR) marathi else english
        var value = source[key] ?: english[key] ?: key
        variables.forEach { (name, replacement) ->
            value = value.replace("{$name}", replacement.toString())
        }
        return value
    }

    fun localizedValue(language: Language, value: String): String {
        return if (language == Language.MR) valueTranslations[value] ?: value else value
    }
